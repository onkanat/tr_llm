    lit_keywords = ["kafiye", "redif", "şiir", "nazım", "edebiyat", "sanat", "roman", "gazel", "koşma", "yazar", "şair"]
    if os.path.exists(hs_path):
        with open(hs_path, "r", encoding="utf-8") as f:
            for line in f:
                if len(records) >= target_count:
                    break
                line = line.strip()
                if not line:
                    continue
